"""scripts/make_results_index.py

docs/results/README.md: the way into every result (plan P11, consolidated pass).
The value map first, then each phase with its verdicts, then each experiment
with its register state, its verdict history and links to its folders and
figures. Generated from src/safari_bands/{experiments,phases,outputs}.py, so it
cannot disagree with the register; tests/test_outputs.py fails when it is stale.

    python scripts/make_results_index.py
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from safari_bands import outputs as O  # noqa: E402
from safari_bands.experiments import EXPERIMENTS, STATES  # noqa: E402
from safari_bands.phases import PHASES  # noqa: E402

OUT = O.RESULTS / "README.md"


def _cell(text: str) -> str:
    return text.replace("|", "/")


def markdown() -> str:
    L = ["# Results index",
         "",
         "Generated by `scripts/make_results_index.py`; do not edit. Each phase folder holds "
         "its figures, tables (`tables.md`, `T_*.csv`), the phase sheet (`experiments.md`, "
         "`experiments.png`) and a README with the reading. Qualitative views per experiment "
         "are listed in [QUALITATIVE_INDEX.md](QUALITATIVE_INDEX.md).",
         "",
         "## Value map",
         "",
         "What substituting each CFFDRS input changed, across the phases so far. Table: "
         "[value_map.md](value_map.md).",
         "",
         "![value map](figures/value_map.png)",
         "",
         "## Phases",
         "",
         "| phase | date | title | verdicts |",
         "|---|---|---|---|"]
    for p in sorted(PHASES, key=lambda p: (p.date, p.pid)):
        c = Counter(e.verdict for e in p.entries)
        v = ", ".join(f"{n} {k}" for k, n in sorted(c.items()))
        L.append(f"| [{p.pid}]({p.folder}/{p.note}) | {p.date} | {_cell(p.title)} | {v} |")
    with_res = O.with_results()
    L += ["",
          "## Experiments",
          "",
          f"{len(with_res)} of {len(EXPERIMENTS)} experiments have a result. The register "
          "state says whether it can run again; the verdicts are what the phases found, oldest "
          "first. Full definitions: [EXPERIMENTS.md](../EXPERIMENTS.md).",
          "",
          "| experiment | register state | verdicts | results | own views |",
          "|---|---|---|---|---|"]
    for x in EXPERIMENTS:
        hist = ", ".join(f"{pid} {v}" for pid, _, v in O.phase_verdicts(x.eid)) or "-"
        dirs = ", ".join(f"[{f}]({f}/)" for f in O.folders(x.eid)) or "-"
        own = ", ".join(f"[{p.stem.removeprefix(f'qual_{x.eid}_')}]({p.parent.name}/{p.name})"
                        for p in O.figures(x.eid) if p.name.startswith(f"qual_{x.eid}_")) or "-"
        L.append(f"| {x.eid} {_cell(x.name)} | {STATES[x.state]['label']} | {hist} | {dirs} | "
                 f"{own} |")
    return "\n".join(L) + "\n"


def main() -> int:
    OUT.write_text(markdown(), encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
